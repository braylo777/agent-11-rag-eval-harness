# Offline dense-retrieval eval on the box CPU with local sentence-transformers models (no Workers AI).
# Writes evals/offline.json and src/offline.js. Metrics match src/metrics.js exactly.
import json, time, datetime, pathlib
from sentence_transformers import SentenceTransformer
root = pathlib.Path(__file__).resolve().parent.parent
D = json.load(open(root / "evals/data.json"))
MODELS = {"all-MiniLM-L6-v2": ("sentence-transformers/all-MiniLM-L6-v2", ""), "bge-small-en-v1.5": ("BAAI/bge-small-en-v1.5", "Represent this sentence for searching relevant passages: "), "bge-base-en-v1.5": ("BAAI/bge-base-en-v1.5", "Represent this sentence for searching relevant passages: ")}
r3 = lambda x: round(x + 1e-12, 3)
def score(rank, qs, ks=(1, 3, 5)):
    o = {"n": len(qs)}
    for k in ks:
        o[f"precision@{k}"] = r3(sum(len(set(rank[q["id"]][:k]) & set(q["relevant"])) / k for q in qs) / len(qs))
        o[f"recall@{k}"] = r3(sum(len(set(rank[q["id"]][:k]) & set(q["relevant"])) / len(q["relevant"]) for q in qs) / len(qs))
    o["mrr"] = r3(sum(next((1 / (i + 1) for i, c in enumerate(rank[q["id"]]) if c in q["relevant"]), 0) for q in qs) / len(qs))
    return o
out = {"run_at": datetime.datetime.now(datetime.timezone.utc).isoformat(), "hardware": "box CPU", "models": {}}
ids = [c["id"] for c in D["chunks"]]
for name, (hf, prefix) in MODELS.items():
    m = SentenceTransformer(hf, device="cpu")
    C = m.encode([c["text"] for c in D["chunks"]], normalize_embeddings=True)
    t = time.perf_counter(); Q = m.encode([prefix + q["q"] for q in D["queries"]], normalize_embeddings=True); ms = (time.perf_counter() - t) * 1000 / len(D["queries"])
    S = Q @ C.T
    rank = {q["id"]: [ids[j] for j in (-S[i]).argsort(kind="stable")] for i, q in enumerate(D["queries"])}
    out["models"][name] = {**score(rank, D["queries"]), "query_embed_ms_mean": round(ms, 1), "hf_id": hf}
    print(name, out["models"][name])
json.dump(out, open(root / "evals/offline.json", "w"), indent=2)
open(root / "src/offline.js", "w").write("// Generated by evals/offline_embed.py (local CPU embeddings). Do not edit by hand.\nexport const OFFLINE = " + json.dumps(out) + ";\n")
